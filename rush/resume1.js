document.addEventListener("DOMContentLoaded", function () {
    // เปิดใช้งาน AOS Animation ที่เราเรียกมาจาก CDN
    AOS.init({
        once: true,       // ให้แอนิเมชันเล่นแค่ครั้งเดียวเวลาเลื่อนลงมาพบ (ถ้าอยากให้เล่นซ้ำทุกครั้งที่เลื่อนผ่าน ให้เปลี่ยนเป็น false)
        offset: 100,      // ระยะห่างจากขอบจอก่อนที่แอนิเมชันจะเริ่มทำงาน (หน่วยเป็น px)
        duration: 800     // ความเร็วในการเล่นแอนิเมชัน (มิลลิวินาที)
    });
});